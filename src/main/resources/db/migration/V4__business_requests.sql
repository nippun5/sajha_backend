CREATE TABLE business_requests (
  id VARCHAR(36) NOT NULL PRIMARY KEY,
  owner_id VARCHAR(36) NOT NULL,
  business_name VARCHAR(100) NOT NULL,
  category VARCHAR(60) NOT NULL,
  contact_phone VARCHAR(16) NOT NULL,
  website VARCHAR(300) NOT NULL DEFAULT '',
  description TEXT NOT NULL,
  online_only BOOLEAN NOT NULL,
  address VARCHAR(250) NOT NULL DEFAULT '',
  latitude DOUBLE NULL,
  longitude DOUBLE NULL,
  place_id VARCHAR(200) NULL,
  city VARCHAR(100) NULL,
  state VARCHAR(100) NULL,
  country_code VARCHAR(8) NULL,
  opening_hours_json LONGTEXT NOT NULL,
  opening_hours_structured_json LONGTEXT NOT NULL,
  banner_storage_key VARCHAR(50) NOT NULL,
  banner_mime VARCHAR(30) NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'pending',
  visibility VARCHAR(16) NOT NULL DEFAULT 'active',
  decline_reason VARCHAR(800) NULL,
  suspension_reason VARCHAR(800) NULL,
  reviewed_at DATETIME(6) NULL,
  reviewed_by VARCHAR(36) NULL,
  payment_confirmed BOOLEAN NOT NULL DEFAULT FALSE,
  payment_verified_at DATETIME(6) NULL,
  payment_verified_by VARCHAR(36) NULL,
  payment_reference VARCHAR(100) NULL,
  payment_note VARCHAR(400) NULL,
  revision INT NOT NULL DEFAULT 1,
  submitted_at DATETIME(6) NOT NULL,
  last_submitted_at DATETIME(6) NOT NULL,
  row_version BIGINT NOT NULL DEFAULT 0,
  CONSTRAINT fk_business_owner FOREIGN KEY(owner_id) REFERENCES app_users(id) ON DELETE CASCADE,
  INDEX idx_business_owner (owner_id, last_submitted_at),
  INDEX idx_business_public (status, visibility, last_submitted_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE business_admin_activity (
  id VARCHAR(36) NOT NULL PRIMARY KEY,
  request_id VARCHAR(36) NOT NULL,
  actor_id VARCHAR(36) NOT NULL,
  action_type VARCHAR(30) NOT NULL,
  detail VARCHAR(800) NOT NULL,
  created_at DATETIME(6) NOT NULL,
  CONSTRAINT fk_business_activity_request FOREIGN KEY(request_id) REFERENCES business_requests(id),
  CONSTRAINT fk_business_activity_actor FOREIGN KEY(actor_id) REFERENCES app_users(id),
  INDEX idx_business_activity_recent (created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
